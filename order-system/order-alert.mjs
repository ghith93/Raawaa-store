/**
 * نص تنبيه المالك — معزول قصدًا عن محرك التسعير.
 *
 * كان `telegram-notifier.mjs` يستورد هذه الدالة من `order-core.mjs`، الذي يستورد
 * بدوره `js/offers.js`. لذلك كان أي بناء لحزمة outbox يسحب محرك العروض والتسعير
 * كاملًا إلى دالة لا تحتاج إلا سطر نص واحد. عزل الدالة يجعل الحزمة أصغر وقابلة
 * لإعادة الإنتاج، ويُبقي واجهة التنبيه بعيدًا عن منطق المال.
 *
 * النص الافتراضي لا يتضمن اسم العميلة ولا هاتفها ولا عنوانها.
 */
export function formatOwnerAlert(reference) {
  if (typeof reference !== 'string' || !/^[A-Z0-9-]{6,40}$/.test(reference)) throw new Error('INVALID_REFERENCE');
  return `طلب جديد بانتظار المراجعة: ${reference}\nافتحي لوحة الطلبات للاطلاع على التفاصيل.`;
}
