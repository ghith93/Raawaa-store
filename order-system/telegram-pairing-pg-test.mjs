import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
import { createTelegramPairingRepository } from './telegram-pairing-repository.mjs';
import { createTelegramPairing } from './telegram-pairing.mjs';
if (!process.env.PGLITE_MODULE) throw new Error('Set PGLITE_MODULE');
const { PGlite } = await import(pathToFileURL(process.env.PGLITE_MODULE));
const db = new PGlite();
await db.exec('create role anon; create role authenticated; create role service_role bypassrls;');
for (const file of ['001_private_orders.sql','002_telegram_pairing.sql']) await db.exec(await readFile(new URL(`./migrations/${file}`, import.meta.url), 'utf8'));
const repository = createTelegramPairingRepository(db);
let message;
const pairing = createTelegramPairing({ repository, botToken:'12345:'+'x'.repeat(25), fetchImpl:async()=>({ok:true,json:async()=>({ok:true,result:message?[message]:[]})}) });
const first=await pairing.start(), firstCode=first.message.split(' ')[1];
const second=await pairing.start(), code=second.message.split(' ')[1];
assert.equal((await repository.find(first.id)), null);
message={message:{text:second.message,date:Math.floor(Date.now()/1000),chat:{id:1234,type:'private'},from:{id:1234}}};
assert.deepEqual(await pairing.finish({id:second.id,code}),{ok:true});
assert.equal((await pairing.finish({id:second.id,code})).error,'invalid');
assert.equal((await db.query('select chat_id from rawaa_store.telegram_recipient')).rows[0].chat_id,1234);
const rows=await db.query("select tablename, rowsecurity from pg_tables where schemaname='rawaa_store' and tablename like 'telegram_%'");
assert.equal(rows.rows.length,2); assert.ok(rows.rows.every(row=>row.rowsecurity));
await assert.rejects(db.exec('set role anon; select * from rawaa_store.telegram_recipient;'));
await db.exec('reset role');
// Fail recipient storage: transaction must roll back consumption as well.
const third=await pairing.start(), thirdCode=third.message.split(' ')[1];
await db.exec("create function rawaa_store.fail_pair() returns trigger language plpgsql as $$ begin raise exception 'test'; end $$; create trigger fail_pair before update or insert on rawaa_store.telegram_recipient for each row execute function rawaa_store.fail_pair();");
message.message.text=third.message;
assert.equal((await pairing.finish({id:third.id,code:thirdCode})).error,'unavailable');
assert.equal((await repository.find(third.id)).consumed,false);
await db.close();
console.log('Telegram pairing: private schema, superseded codes, single use and atomic rollback passed.');
