import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { createPostgresRepository } from './postgres-repository.mjs';
import { createOutboxRunner } from './outbox-runner.mjs';
if (!process.env.PGLITE_MODULE) throw new Error('Set PGLITE_MODULE');
const { PGlite } = await import(pathToFileURL(process.env.PGLITE_MODULE));
const db = new PGlite();
await db.exec('create role anon; create role authenticated; create role service_role bypassrls;');
await db.exec(await readFile(new URL('./migrations/001_private_orders.sql', import.meta.url), 'utf8'));
const repo = createPostgresRepository(db);
const token = '123456:' + 'x'.repeat(25), chatId = '123456789';
const ids = ['11111111-1111-4111-8111-111111111111','22222222-2222-4222-8222-222222222222','33333333-3333-4333-8333-333333333333','44444444-4444-4444-8444-444444444444'];
const saved = [];
for (const idempotencyKey of ids) saved.push(await repo.insertPending({ idempotencyKey, order: { name: 'Test', phone: '0990000000', address: 'Test', entries: [], scent: '', oil: '', zone: 'hama', method: 'cod' } }));
let sends = 0;
const successFetch = async (_url, init) => {
  sends++;
  const body = JSON.parse(init.body);
  assert.equal(body.chat_id, chatId);
  assert.match(body.text, /بانتظار المراجعة/);
  assert.ok(!body.text.includes('0991234567'));
  return { ok: true, json: async () => ({ ok: true, result: { message_id: 17, chat: { id: 123456789 } } }) };
};
const worker = createOutboxRunner({ db, token, chatId, fetchImpl: successFetch });
const concurrent = await Promise.all([worker.kick(saved[0].reference), worker.kick(saved[0].reference)]);
assert.deepEqual(concurrent.map(r => r.state).sort(), ['no_pending', 'sent']);
assert.equal(sends, 1);
const timedOut = createOutboxRunner({ db, token, chatId, fetchImpl: async () => { throw new Error(token); } });
assert.equal((await timedOut.kick(saved[1].reference)).state, 'unknown');
assert.equal((await worker.kick(saved[1].reference)).state, 'no_pending');
const reject = createOutboxRunner({ db, token, chatId, fetchImpl: async () => ({ ok: true, json: async () => ({ ok: false }) }) });
assert.equal((await reject.kick(saved[2].reference)).state, 'failed');
assert.equal((await worker.kick(saved[2].reference)).state, 'no_pending');
// Simulate process death after claiming but before a durable result.
await db.query(`update rawaa_store.notification_outbox q set state='sending', lease_until=now()-interval '1 second', lease_id=$1, attempts=1 from rawaa_store.orders o where q.order_id=o.id and o.reference=$2`, [crypto.randomUUID(), saved[3].reference]);
assert.equal((await worker.recoverExpired()).count, 1);
assert.equal((await worker.kick(saved[3].reference)).state, 'no_pending');
const states = await db.query('select state, count(*)::int as n from rawaa_store.notification_outbox group by state order by state');
assert.deepEqual(states.rows, [{ state: 'failed', n: 1 }, { state: 'sent', n: 1 }, { state: 'unknown', n: 2 }]);
await db.close();
console.log('Ephemeral PostgreSQL: duplicate claims, successful send, failures and expired leases passed.');
