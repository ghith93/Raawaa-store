#!/usr/bin/env node
// يبني حزمة استقبال الطلبات من المصادر الحالية. التشغيل: node scripts/build-order-entry.mjs
// 1) يقرأ js/config.js (مصدر الأسعار الوحيد) ويولّد store-config.generated.mjs مع بصمة.
// 2) يجمّع order-entry.mjs بـesbuild إلى order-entry-bundle.mjs (بلا أسرار، npm:postgres خارجي).
// الحزمة تُرافق الفرع لتوثيق النشر المستقبلي؛ اختبار order-entry-bundle.test.mjs
// يفشل إذا بقيت الحزمة قديمة بعد أي تغيير في الأسعار.
import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { loadStoreConfig } from '../order-system/store-config.mjs';

const root = new URL('..', import.meta.url);
const config = await loadStoreConfig();
const json = JSON.stringify(config);
const hash = createHash('sha256').update(json).digest('hex');
const generated = `// Generated by scripts/build-order-entry.mjs — do not edit, do not commit.\n` +
  `export const RAWAA_CONFIG_HASH = '${hash}';\n` +
  `export const RAWAA_STORE_CONFIG = JSON.parse(${JSON.stringify(json)});\n`;
await writeFile(new URL('order-system/edge/store-config.generated.mjs', root), generated, 'utf8');

execFileSync('npx', ['--yes', 'esbuild',
  'order-system/edge/order-entry.mjs',
  '--bundle', '--format=esm', '--minify', '--charset=utf8',
  '--external:npm:postgres@3.4.7',
  '--outfile=order-system/edge/order-entry-bundle.mjs'], { cwd: root, stdio: 'inherit' });

console.log(`✓ order-entry-bundle.mjs — config hash ${hash.slice(0, 12)}…`);
